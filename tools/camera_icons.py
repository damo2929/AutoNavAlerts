"""
The camera icon set (DESIGN.md §7.1, owner 2026-10-25): turns the original glyph SVGs in
art/icons/glyph_<type>.svg into Android vector drawables (app/src/main/res/drawable/ic_cam_glyph_<type>.xml)
and writes preview SVGs of every type and limit to art/icons/preview/, plus one sheet (all.svg).

The glyphs are the only source; nothing here or there is taken from the PocketGPSWorld icons (hard rule 6).
The layout numbers (roundel, ring, tab, text sizes, colours) must match CameraIconPainter.kt, which
draws the same icon on the phone; change both together.

Usage:  tools/camera_icons.py            (from the repo root; rewrites the drawables and the previews)
Only <path>, <circle> and <rect> are read, with fill, fill-rule, stroke, stroke-width, stroke-linecap,
stroke-linejoin; that is all the glyphs use.
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art", "icons")
DRAWABLE = os.path.join(ROOT, "app", "src", "main", "res", "drawable")
SVG_NS = "{http://www.w3.org/2000/svg}"

# type → (tab colour, glyph colour on the tab); temporary cameras use TEMPORARY for the tab (§7.1).
# Fixed and average (SPECS) are the UK speed-camera sign (owner, 2026-10-25): the tab is the sign's panel,
# white or yellow, and the glyph its black frame and camera; see SIGN_TYPES and SIGN below.
TYPES = {
    "fixed": ("#FFFFFF", "#000000"),
    "mobile": ("#FFFFFF", "#000000"),
    "average": ("#F2B705", "#000000"),
    "redlight": ("#FFFFFF", "#000000"),
    "redlight_speed": ("#C62828", "#FFFFFF"),
    "pending": ("#FFFFFF", "#757575"),
}
# The traffic lights' lamps (cx, cy, r in glyph units, colour; CameraType.lamps): red, amber, green (§7.1).
LAMP_COLOURS = ("#E53935", "#FDD835", "#43A047")
LAMPS = {
    "redlight": [(12.0, y, 2.0, c) for y, c in zip((6.0, 11.2, 16.4), LAMP_COLOURS)],
    "redlight_speed": [(5.75, y, 1.6, c) for y, c in zip((6.4, 11.2, 16.0), LAMP_COLOURS)],
}
TEMPORARY = "#EF6C00"
RING = "#D32F2F"
INK = "#212121"

# Types drawn as the sign; types that borrow another's glyph (average: the sign; pending: the mobile camera).
SIGN_TYPES = {"fixed", "average"}
GLYPH_OF = {"average": "fixed", "pending": "mobile"}
# Types drawn bare: the glyph alone on a backing, no roundel or limit (red light; CameraType.bare).
BARE_TYPES = {"redlight"}
BARE = dict(glyph=46.0, backing=(5.6, 0.3, 18.4, 23.7))
# The sign glyph's frame as fractions of the glyph, and its corner radius in glyph units (CameraIconPainter.SIGN_*).
SIGN = dict(w=23 / 24, h=19.68 / 24, rx=2.84)

# The 48-unit layout (mirrored in CameraIconPainter.kt).
WITH_LIMIT = dict(cx=21.0, cy=21.0, r=20.0, ring_r=17.0, ring_w=4.2, tab=(27.0, 27.0, 20.0, 5.0), text2=17.0, text3=12.0)


def circle_path(cx, cy, r):
    return f"M{cx - r:g} {cy:g}a{r:g} {r:g} 0 1 0 {2 * r:g} 0a{r:g} {r:g} 0 1 0 {-2 * r:g} 0z"


def rect_path(x, y, w, h, rx=0.0):
    if rx <= 0:
        return f"M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}z"
    return (f"M{x + rx:g} {y:g}h{w - 2 * rx:g}a{rx:g} {rx:g} 0 0 1 {rx:g} {rx:g}v{h - 2 * rx:g}"
            f"a{rx:g} {rx:g} 0 0 1 {-rx:g} {rx:g}h{-(w - 2 * rx):g}a{rx:g} {rx:g} 0 0 1 {-rx:g} {-rx:g}"
            f"v{-(h - 2 * rx):g}a{rx:g} {rx:g} 0 0 1 {rx:g} {-rx:g}z")


def shapes(svg_file):
    """The glyph's drawable shapes as dicts: d, fill (bool), evenodd, stroke width/cap/join."""
    out = []
    for el in ET.parse(svg_file).getroot().iter():
        tag = el.tag.replace(SVG_NS, "")
        # The lit lamp is a second colour the painter draws itself (LAMPS), not part of the tinted drawable.
        if (el.get("id") or "").startswith("lamp"):
            continue
        if tag == "path":
            d = el.get("d")
        elif tag == "circle":
            d = circle_path(float(el.get("cx")), float(el.get("cy")), float(el.get("r")))
        elif tag == "rect":
            d = rect_path(float(el.get("x", 0)), float(el.get("y", 0)), float(el.get("width")), float(el.get("height")), float(el.get("rx", 0)))
        else:
            continue
        out.append(dict(
            d=d,
            fill=el.get("fill", "#000") != "none",
            evenodd=el.get("fill-rule") == "evenodd",
            stroke=el.get("stroke") not in (None, "none"),
            width=el.get("stroke-width", "1"),
            cap=el.get("stroke-linecap", "butt"),
            join=el.get("stroke-linejoin", "miter"),
        ))
    return out


def vector_drawable(name, items):
    """An Android vector drawable, 24 dp, black: the painter tints it (DESIGN.md §7.1)."""
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Copyright 2026 Damien Dye",
        "     SPDX-License-Identifier: Apache-2.0",
        f"     Generated by tools/camera_icons.py from art/icons/glyph_{name}.svg (DESIGN.md §7.1); edit the SVG, not this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">',
    ]
    for s in items:
        attrs = [f'android:pathData="{s["d"]}"']
        if s["fill"]:
            attrs.append('android:fillColor="#FF000000"')
            if s["evenodd"]:
                attrs.append('android:fillType="evenOdd"')
        if s["stroke"]:
            attrs += ['android:strokeColor="#FF000000"', f'android:strokeWidth="{s["width"]}"',
                      f'android:strokeLineCap="{s["cap"]}"', f'android:strokeLineJoin="{s["join"]}"']
        lines.append("    <path " + " ".join(attrs) + " />")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def glyph_svg(items, colour, x, y, size):
    k = size / 24.0
    parts = [f'<g transform="translate({x:g} {y:g}) scale({k:g})">']
    for s in items:
        fill = colour if s["fill"] else "none"
        rule = ' fill-rule="evenodd"' if s["evenodd"] else ""
        stroke = (f' stroke="{colour}" stroke-width="{s["width"]}" stroke-linecap="{s["cap"]}" stroke-linejoin="{s["join"]}"'
                  if s["stroke"] else "")
        parts.append(f'<path d="{s["d"]}" fill="{fill}"{rule}{stroke}/>')
    parts.append("</g>")
    return "".join(parts)


def type_glyph_svg(type_name, items, colour, x, y, size):
    """The type's glyph at (x, y), size square, then its lamps in colour in the same box (CameraIconPainter.typeGlyph)."""
    u = size / 24.0
    lamps = "".join(f'<circle cx="{x + cx * u:g}" cy="{y + cy * u:g}" r="{r * u:g}" fill="{c}"/>' for cx, cy, r, c in LAMPS.get(type_name, []))
    return glyph_svg(items, colour, x, y, size) + lamps


def icon_svg(type_name, items, limit, temporary=False):
    """One composite icon (48 units) as the painter draws it: a roundel with the limit ("*" when none is known) and a type tab."""
    out = ['<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48">']
    if type_name in BARE_TYPES:
        # The glyph alone on its backing: no roundel, no limit (CameraIconPainter.bare).
        g = BARE["glyph"]; u = g / 24; left = top = 24 - g / 2
        bl, bt, br, bb = BARE["backing"]
        tab, ink = TYPES[type_name]
        out.append(f'<rect x="{left + bl * u:g}" y="{top + bt * u:g}" width="{(br - bl) * u:g}" height="{(bb - bt) * u:g}" rx="{3.5 * u:g}" fill="{TEMPORARY if temporary else tab}"/>')
        out.append(type_glyph_svg(type_name, items, ink, left, top, g))
        out.append("</svg>")
        return "".join(out)
    L = WITH_LIMIT
    out.append(f'<circle cx="{L["cx"]}" cy="{L["cy"]}" r="{L["r"]}" fill="#FFFFFF"/>')
    out.append(f'<circle cx="{L["cx"]}" cy="{L["cy"]}" r="{L["ring_r"]}" fill="none" stroke="{RING}" stroke-width="{L["ring_w"]}"/>')
    # "*" (no limit known, §7.1) is larger and sits high, so it is centred lower than the digits.
    star = limit == "*"
    size = 28.0 if star else L["text2"] if len(limit) <= 2 else L["text3"]
    out.append(f'<text x="{L["cx"]}" y="{L["cy"] + size * (0.5 if star else 0.36):g}" font-family="Roboto Condensed, Arial Narrow, sans-serif" '
               f'font-weight="bold" font-size="{size}" text-anchor="middle" fill="{INK}">{limit}</text>')
    x, y, w, rx = L["tab"]
    tab, ink = TYPES[type_name]
    fill = TEMPORARY if temporary else tab
    if type_name in SIGN_TYPES:
        # The sign's own shape in the bottom-right corner, its panel under the glyph's frame.
        sw, sh = w * SIGN["w"], w * SIGN["h"]
        sx, sy, srx = x + w - sw, y + w - sh, SIGN["rx"] * w / 24
        out.append(f'<rect x="{sx:g}" y="{sy:g}" width="{sw:g}" height="{sh:g}" rx="{srx:g}" fill="{fill}" stroke="#FFFFFF" stroke-width="1.5"/>')
        out.append(type_glyph_svg(type_name, items, ink, sx + sw / 2 - w / 2, sy + sh / 2 - w / 2, w))
    else:
        out.append(f'<rect x="{x}" y="{y}" width="{w}" height="{w}" rx="{rx}" fill="{fill}" stroke="#FFFFFF" stroke-width="1.5"/>')
        g = w * 0.72
        gx, gy = x + (w - g) / 2, y + (w - g) / 2
        out.append(type_glyph_svg(type_name, items, "#FFFFFF" if temporary else ink, gx, gy, g))
    out.append("</svg>")
    return "".join(out)


def main():
    os.makedirs(os.path.join(ART, "preview"), exist_ok=True)
    glyphs = {}
    for name in TYPES:
        source = GLYPH_OF.get(name, name)
        items = shapes(os.path.join(ART, f"glyph_{source}.svg"))
        glyphs[name] = items
        if source == name:
            with open(os.path.join(DRAWABLE, f"ic_cam_glyph_{name}.xml"), "w") as f:
                f.write(vector_drawable(name, items))
    limits = ["20", "30", "40", "50", "60", "70", "VAR", "*"]
    cells = []
    for row, name in enumerate(TYPES):
        for col, limit in enumerate(limits):
            svg = icon_svg(name, glyphs[name], limit)
            label = {"*": "none"}.get(limit, limit.lower())
            with open(os.path.join(ART, "preview", f"{name}_{label}.svg"), "w") as f:
                f.write(svg)
            cells.append((col, row, svg))
        temp = icon_svg(name, glyphs[name], "50", temporary=True)
        with open(os.path.join(ART, "preview", f"{name}_temporary_50.svg"), "w") as f:
            f.write(temp)
        cells.append((len(limits), row, temp))
    # One sheet: rows are types, columns are limits, the last column a temporary camera.
    cw = 56
    sheet = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{cw * (len(limits) + 1)}" height="{cw * len(TYPES)}">',
             f'<rect width="100%" height="100%" fill="#9E9E9E"/>']
    for col, row, svg in cells:
        inner = re.sub(r"^<svg[^>]*>|</svg>$", "", svg)
        sheet.append(f'<g transform="translate({col * cw + 4} {row * cw + 4})">{inner}</g>')
    sheet.append("</svg>")
    with open(os.path.join(ART, "preview", "all.svg"), "w") as f:
        f.write("".join(sheet))
    print(f"{len(set(GLYPH_OF.get(t, t) for t in TYPES))} drawables, {len(cells)} previews")


if __name__ == "__main__":
    sys.exit(main())
